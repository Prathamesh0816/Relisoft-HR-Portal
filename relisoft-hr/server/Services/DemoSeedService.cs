            {
                db.RecognitionAwardRecipients.Add(new RecognitionAwardRecipient
                {
                    AwardId = 1,
                    EmployeeId = emp.Id,
                    RecognitionType = "Individual",
                    Reason = "Consistent high-quality delivery and team support.",
                    AwardedOn = utcNow(),
                    AwardedByEmployeeId = creator.Id
                });
            }
            await db.SaveChangesAsync();
        }

        if (!await db.Kudos.AnyAsync())
        {
            var giver = await db.Employees.OrderBy(e => e.Id).FirstOrDefaultAsync();
            var giverId = giver?.Id;
            var receiver = await db.Employees.Where(e => e.Id != (giverId ?? 0)).OrderBy(e => e.Id).FirstOrDefaultAsync();
            if (giver != null && receiver != null)
            {
                db.Kudos.Add(new Kudos
                {
                    GiverEmployeeId = giver.Id,
                    ReceiverEmployeeId = receiver.Id,
                    Category = "Teamwork",
                    Message = "Great collaboration on the release!",
                    Points = 10,
                    CreatedOn = utcNow()
                });
                await db.SaveChangesAsync();
            }
        }

        return r;
    }

