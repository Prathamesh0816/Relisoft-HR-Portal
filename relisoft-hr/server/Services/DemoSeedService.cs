                            'Individual', 'Monthly', {now.ToString("MMM yyyy")}, '', 100, {now}, {creator.Id});
                    SET IDENTITY_INSERT RecognitionAwards OFF;");
            }
            r = r with { Awards = r.Awards + 1 };
        }

        if (!await db.RecognitionAwardRecipients.AnyAsync(rec => rec.AwardId == 1))
        {
            var recipients = await db.Employees.Where(e => e.Id == 3 || e.Id == 7).ToListAsync();
