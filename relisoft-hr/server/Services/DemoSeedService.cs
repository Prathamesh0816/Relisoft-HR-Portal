    // ------------------------------------------------------------------
    // Attendance records for the last two weeks.
    // ------------------------------------------------------------------
    private static async Task<SeedReport> SeedAttendanceAsync(AppDbContext db, SeedReport r, DateTime utc, DateOnly today)
    {
        if (await db.AttendanceRecords.AnyAsync()) return r;

        var employees = await db.Employees.Where(e => e.Status == "Active" || e.Status == "Onboarding" || e.Status == null).Select(e => e.Id).ToListAsync();
        var start = DateTime.UtcNow.Date.AddDays(-10);
        var added = 0;
        for (var i = 0; i < 10 && added < 200; i++)
        {
            var day = start.AddDays(i);
            if (day.DayOfWeek == DayOfWeek.Saturday || day.DayOfWeek == DayOfWeek.Sunday) continue;
            foreach (var employeeId in employees)
            {
                if (added >= 200) break;
                var clockIn = day.AddHours(9).AddMinutes(10);
                var clockOut = day.AddHours(18).AddMinutes(15);
                db.AttendanceRecords.Add(new AttendanceRecord
                {
                    EmployeeId = employeeId,
                    Date = day,
                    ClockIn = clockIn,
                    ClockOut = clockOut,
                    Status = "Present",
                    Notes = "Demo seeded attendance",
                    CreatedOn = utc
                });
                added++;
            }
        }
        await db.SaveChangesAsync();
        return r with { Attendance = r.Attendance + added };
    }

